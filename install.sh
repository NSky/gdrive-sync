#!/bin/bash
# linux-gdrive-sync installer
#
# This script installs the linux-gdrive-sync tools and configures them
# for your system. It will:
# 1. Check for required dependencies (rclone, inotify-tools, jq)
# 2. Install missing dependencies
# 3. Prompt for configuration
# 4. Install scripts and systemd units
# 5. Optionally run initial setup

set -euo pipefail

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Installation paths
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN_DIR="$HOME/.local/bin"
CONFIG_DIR="$HOME/.config/gdrive-sync"
SYSTEMD_DIR="$HOME/.config/systemd/user"
STATE_DIR="$HOME/.local/state/gdrive-sync"

# Default configuration
DEFAULT_LOCAL="$HOME/gdrive"
DEFAULT_REMOTE="gdrive:"

log_info() {
    echo -e "${BLUE}[INFO]${NC} $*"
}

log_success() {
    echo -e "${GREEN}[OK]${NC} $*"
}

log_warn() {
    echo -e "${YELLOW}[WARN]${NC} $*"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $*"
}

check_command() {
    command -v "$1" &>/dev/null
}

# === Dependency Check ===

check_dependencies() {
    log_info "Checking dependencies..."

    local missing=()

    if ! check_command rclone; then
        missing+=("rclone")
    else
        log_success "rclone found: $(rclone --version | head -1)"
    fi

    if ! check_command inotifywait; then
        missing+=("inotify-tools")
    else
        log_success "inotifywait found"
    fi

    if ! check_command jq; then
        missing+=("jq")
    else
        log_success "jq found"
    fi

    if [[ ${#missing[@]} -gt 0 ]]; then
        log_warn "Missing dependencies: ${missing[*]}"
        install_dependencies "${missing[@]}"
    fi
}

install_dependencies() {
    local deps=("$@")

    echo ""
    log_info "Attempting to install missing dependencies..."

    # Detect package manager
    if check_command apt-get; then
        log_info "Using apt-get..."
        for dep in "${deps[@]}"; do
            if [[ "$dep" == "rclone" ]]; then
                sudo apt-get update && sudo apt-get install -y rclone
            elif [[ "$dep" == "inotify-tools" ]]; then
                sudo apt-get install -y inotify-tools
            elif [[ "$dep" == "jq" ]]; then
                sudo apt-get install -y jq
            fi
        done
    elif check_command brew; then
        log_info "Using Homebrew..."
        for dep in "${deps[@]}"; do
            if [[ "$dep" == "inotify-tools" ]]; then
                brew install inotify-tools
            else
                brew install "$dep"
            fi
        done
    elif check_command dnf; then
        log_info "Using dnf..."
        for dep in "${deps[@]}"; do
            if [[ "$dep" == "inotify-tools" ]]; then
                sudo dnf install -y inotify-tools
            else
                sudo dnf install -y "$dep"
            fi
        done
    elif check_command pacman; then
        log_info "Using pacman..."
        for dep in "${deps[@]}"; do
            sudo pacman -S --noconfirm "$dep"
        done
    else
        log_error "Could not detect package manager. Please install manually:"
        for dep in "${deps[@]}"; do
            echo "  - $dep"
        done
        exit 1
    fi

    # Verify installation
    log_info "Verifying dependencies..."
    local still_missing=()

    for dep in "${deps[@]}"; do
        local cmd="$dep"
        [[ "$dep" == "inotify-tools" ]] && cmd="inotifywait"

        if ! check_command "$cmd"; then
            still_missing+=("$dep")
        fi
    done

    if [[ ${#still_missing[@]} -gt 0 ]]; then
        log_error "Failed to install: ${still_missing[*]}"
        exit 1
    fi

    log_success "All dependencies installed!"
}

# === Configuration ===

configure() {
    echo ""
    echo "=========================================="
    echo "  linux-gdrive-sync Configuration"
    echo "=========================================="
    echo ""

    # Local directory
    read -rp "Local sync directory [$DEFAULT_LOCAL]: " LOCAL_DIR
    LOCAL_DIR="${LOCAL_DIR:-$DEFAULT_LOCAL}"

    # Remote name
    read -rp "rclone remote name [$DEFAULT_REMOTE]: " REMOTE_NAME
    REMOTE_NAME="${REMOTE_NAME:-$DEFAULT_REMOTE}"

    # Ensure remote name ends with :
    [[ "$REMOTE_NAME" != *: ]] && REMOTE_NAME="${REMOTE_NAME}:"

    echo ""
    log_info "Configuration:"
    echo "  Local directory: $LOCAL_DIR"
    echo "  Remote name: $REMOTE_NAME"
    echo ""

    read -rp "Is this correct? [Y/n]: " confirm
    if [[ "${confirm,,}" == "n" ]]; then
        configure
        return
    fi

    # Save configuration
    mkdir -p "$CONFIG_DIR"

    cat > "$CONFIG_DIR/config.env" <<EOF
# linux-gdrive-sync configuration
# Generated by installer on $(date)

# Local directory to sync with Google Drive
GDRIVE_LOCAL="$LOCAL_DIR"

# rclone remote name (as configured in rclone config)
GDRIVE_REMOTE="$REMOTE_NAME"

# State directory for logs, status, and lock tracking
GDRIVE_STATE_DIR="$STATE_DIR"

# Path to bisync filters file
GDRIVE_FILTERS="$CONFIG_DIR/bisync-filters.txt"

# Maximum consecutive failures before forcing a full resync
GDRIVE_MAX_FAILURES=6

# Lock timeout in minutes
GDRIVE_LOCK_TIMEOUT=10

# Debounce delay in seconds for the file watcher
GDRIVE_DEBOUNCE_SEC=5
EOF

    log_success "Configuration saved to $CONFIG_DIR/config.env"
}

# === rclone Remote Setup ===

check_rclone_remote() {
    local remote="${REMOTE_NAME%:}"

    if rclone listremotes | grep -q "^${remote}:$"; then
        log_success "rclone remote '$remote' exists"
        return 0
    else
        log_warn "rclone remote '$remote' not found"
        return 1
    fi
}

setup_rclone_remote() {
    local remote="${REMOTE_NAME%:}"

    echo ""
    log_info "You need to configure an rclone remote for Google Drive."
    echo ""
    echo "This will open an interactive configuration wizard."
    echo "Choose 'Google Drive' as the storage type."
    echo ""

    read -rp "Run 'rclone config' now? [Y/n]: " run_config
    if [[ "${run_config,,}" != "n" ]]; then
        rclone config

        if ! check_rclone_remote; then
            log_error "Remote '$remote' still not configured. Please run 'rclone config' manually."
            exit 1
        fi
    else
        log_warn "Please configure rclone manually before running the sync."
        echo "Run: rclone config"
    fi
}

# === Installation ===

install_files() {
    log_info "Installing files..."

    # Create directories
    mkdir -p "$BIN_DIR" "$CONFIG_DIR" "$SYSTEMD_DIR" "$STATE_DIR/logs"

    # Install scripts
    cp "$SCRIPT_DIR/bin/gdrive-sync" "$BIN_DIR/"
    cp "$SCRIPT_DIR/bin/gdrive-watch" "$BIN_DIR/"
    cp "$SCRIPT_DIR/bin/gdrive-initial-resync" "$BIN_DIR/"
    chmod +x "$BIN_DIR/gdrive-sync" "$BIN_DIR/gdrive-watch" "$BIN_DIR/gdrive-initial-resync"
    log_success "Scripts installed to $BIN_DIR/"

    # Install filters (if not exists)
    if [[ ! -f "$CONFIG_DIR/bisync-filters.txt" ]]; then
        cp "$SCRIPT_DIR/filters/bisync-filters.txt" "$CONFIG_DIR/"
        log_success "Filter file installed to $CONFIG_DIR/"
    else
        log_info "Filter file already exists, keeping existing"
    fi

    # Install systemd units
    cp "$SCRIPT_DIR/systemd/"*.service "$SYSTEMD_DIR/"
    cp "$SCRIPT_DIR/systemd/"*.timer "$SYSTEMD_DIR/"
    log_success "Systemd units installed to $SYSTEMD_DIR/"

    # Reload systemd
    systemctl --user daemon-reload
    log_success "Systemd daemon reloaded"

    # Create local sync directory
    mkdir -p "$LOCAL_DIR"
    log_success "Local directory created: $LOCAL_DIR"

    # Ensure ~/.local/bin is in PATH
    if [[ ":$PATH:" != *":$BIN_DIR:"* ]]; then
        log_warn "$BIN_DIR is not in your PATH"
        echo ""
        echo "Add this line to your ~/.bashrc or ~/.zshrc:"
        echo "  export PATH=\"\$HOME/.local/bin:\$PATH\""
        echo ""
    fi
}

# === Initial Resync ===

run_initial_resync() {
    echo ""
    log_info "Running initial resync to establish bisync baseline..."
    log_info "This may take a while depending on your Google Drive contents."
    echo ""

    if "$BIN_DIR/gdrive-initial-resync"; then
        log_success "Initial resync completed!"
    else
        log_error "Initial resync failed. Check logs at $STATE_DIR/logs/"
        echo "You can retry with: gdrive-initial-resync"
    fi
}

# === Enable Services ===

enable_services() {
    echo ""
    log_info "Enabling systemd services..."

    systemctl --user enable gdrive-sync.timer
    systemctl --user enable gdrive-fullsync.timer
    systemctl --user enable gdrive-watch.service

    log_success "Services enabled"

    read -rp "Start services now? [Y/n]: " start_now
    if [[ "${start_now,,}" != "n" ]]; then
        systemctl --user start gdrive-sync.timer
        systemctl --user start gdrive-fullsync.timer
        systemctl --user start gdrive-watch.service

        log_success "Services started!"
        echo ""
        echo "Check status with:"
        echo "  systemctl --user status gdrive-sync.timer"
        echo "  systemctl --user status gdrive-watch.service"
    fi
}

# === Main ===

main() {
    echo ""
    echo "=========================================="
    echo "  linux-gdrive-sync Installer"
    echo "=========================================="
    echo ""

    # Check dependencies
    check_dependencies

    # Configure
    configure

    # Check rclone remote
    if ! check_rclone_remote; then
        setup_rclone_remote
    fi

    # Install files
    install_files

    # Initial resync
    echo ""
    read -rp "Run initial resync now? (Recommended for first install) [Y/n]: " do_resync
    if [[ "${do_resync,,}" != "n" ]]; then
        run_initial_resync
    fi

    # Enable services
    enable_services

    echo ""
    echo "=========================================="
    log_success "Installation complete!"
    echo "=========================================="
    echo ""
    echo "Your Google Drive will now sync with: $LOCAL_DIR"
    echo ""
    echo "Useful commands:"
    echo "  gdrive-sync            - Manual sync"
    echo "  gdrive-initial-resync  - Full resync (recovery)"
    echo "  cat $STATE_DIR/status.json - Check sync status"
    echo ""
    echo "Logs: $STATE_DIR/logs/"
    echo "Config: $CONFIG_DIR/config.env"
    echo ""
}

main "$@"
